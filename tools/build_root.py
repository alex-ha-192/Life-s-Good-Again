"""Bundle the rooted-TV part of the kit.

    python3 tools/build_root.py        -> root/settings.json and dist/lgkit-root.tar.gz

settings.json is the privacy-settings list from lgtv_privacy.py, for the on-TV guard.
lgkit-root.tar.gz holds everything install.sh needs on the TV (root/, the .hosts lists, the
Tiles Home .ipk). setup.py --root sends it over SSH; you can also copy it over by hand:
    scp dist/lgkit-root.tar.gz root@TV:/tmp/ && ssh root@TV
    mkdir -p /tmp/kit && tar -xzf /tmp/lgkit-root.tar.gz -C /tmp/kit && sh /tmp/kit/root/install.sh
"""
import io
import json
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import lgtv_privacy  # noqa: E402


def settings_json():
    items = [{"category": c, "key": k, "value": v, "label": label.split(" (")[0]}
             for _p, c, k, v, label in lgtv_privacy.SETTINGS]
    data = {"comment": "Generated by tools/build_root.py from lgtv_privacy.SETTINGS. "
                       "Keys the TV doesn't report are skipped.", "settings": items}
    (ROOT / "root" / "settings.json").write_text(json.dumps(data, indent=1) + "\n")
    return items


def bundle():
    files = sorted(p for p in (ROOT / "root").iterdir() if p.is_file())
    files += sorted((ROOT / "blocklist").glob("*.hosts"))
    ipks = sorted((ROOT / "dist").glob("io.github.lgprivacykit.tiles_*.ipk"), key=lambda p: p.stat().st_mtime)
    files += ipks[-1:]
    # Life's Good Without Spying, if setup.py downloaded it (and its checksum) on this computer
    files += [p for p in (ROOT / "dist" / "ooo.lew.lifesgoodwithoutspying.ipk",
                          ROOT / "dist" / "ooo.lew.lifesgoodwithoutspying.ipk.sha256") if p.exists()]
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for f in files:
            info = t.gettarinfo(str(f), arcname=str(f.relative_to(ROOT)))
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.mode = 0o755 if f.suffix in (".sh", ".js") else 0o644
            with open(f, "rb") as fh:
                t.addfile(info, fh)
    out = ROOT / "dist" / "lgkit-root.tar.gz"
    out.parent.mkdir(exist_ok=True)
    out.write_bytes(buf.getvalue())
    return out, files


if __name__ == "__main__":
    n = len(settings_json())
    out, files = bundle()
    print(f"root/settings.json: {n} settings")
    print(f"{out.relative_to(ROOT)}: {len(files)} files, {out.stat().st_size // 1024} KB"
          + ("" if any(f.suffix == ".ipk" for f in files) else "  (no .ipk yet: run tools/build_ipk.py first)"))
